-- 0001_topics (up): topic classification of affairs for OpenParlData.
-- Proposed by Querschnitt (Hack Apertus Liebefeld, Oct 2026). PostgreSQL 13+.
--
-- Conventions taken from OPD's tables and bulk exports: snake_case; integer `id` primary keys; `<entity>_id` foreign keys
-- with the readable key kept beside them (`body_id` + `body_key`, as in affairs, texts, external_links); language columns
-- `_de/_fr/_it/_rm`; `created_at` / `updated_at` as `timestamp` (without time zone) holding UTC, as in the exports.
--
-- Three tables:
--   topic_schemes  one row per scheme version (APS, a parliament's own scheme, an ad-hoc topic): licence and source
--   topic_codes    the codes of a scheme with their labels de/fr/it/rm and parent (chapter of a subtopic)
--   topics         one row per affair x scheme x level x rank x version: a machine suggestion or a published decision
--
-- Versioning: a topics row is never edited in place except to close it (`valid_to`). A re-score or a decision adds a row.
-- `valid_to IS NULL` = current. Machine rows have provenance 'inferred' and status 'suggested'; a published decision
-- (confirmation or rejection) is a row with provenance 'confirmed', who and when.

BEGIN;

CREATE TABLE IF NOT EXISTS topic_schemes (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scheme_key       text        NOT NULL,                 -- aps · be-directorates · adhoc/digitalisierung
  version          text        NOT NULL,                 -- sha256[:8] of the scheme file that defines the codes
  type             text        NOT NULL CHECK (type IN ('standard', 'body', 'adhoc')),
                                                          -- standard: shared two-level scheme (APS); body: one parliament's
                                                          -- own scheme (e.g. Bern's directorates); adhoc: a yes/no topic
  levels           smallint    NOT NULL CHECK (levels IN (1, 2)),
  name_de          text,
  name_fr          text,
  name_it          text,
  name_rm          text,
  name_en          text,
  question_de      text,                                 -- adhoc only: the question with its scope note, as asked
  question_fr      text,
  question_it      text,
  body_id          integer REFERENCES bodies (id),        -- type 'body': the parliament the scheme belongs to
  body_key         text,
  licence          text,                                 -- SPDX id of the codes and labels; NULL = to be agreed with the source
  source_name      text        NOT NULL,                 -- who publishes the codes (Année Politique Suisse, Kanton Bern, ...)
  source_url       text,
  notes            text,                                 -- e.g. "Italian labels: unofficial translation"
  code_count       integer,
  active           boolean     NOT NULL DEFAULT true,    -- the version new rows are written with
  created_at       timestamp   NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  updated_at       timestamp   NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  CONSTRAINT topic_schemes_key_version UNIQUE (scheme_key, version)
);
CREATE UNIQUE INDEX IF NOT EXISTS topic_schemes_one_active ON topic_schemes (scheme_key) WHERE active;

CREATE TABLE IF NOT EXISTS topic_codes (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scheme_id        integer     NOT NULL REFERENCES topic_schemes (id) ON DELETE CASCADE,
  scheme_key       text        NOT NULL,
  code             text        NOT NULL,                 -- aps:1.7.2. · aps:kw:1374918 · aps:none · adhoc/digitalisierung:yes
  level            smallint    NOT NULL CHECK (level IN (1, 2)),
  parent_code      text,                                 -- level 2: the chapter code
  position         smallint    NOT NULL,                 -- order in the published scheme
  external_id      text,                                 -- the publisher's own identifier (APS: 1.7.2. / keyword id)
  label_de         text,
  label_fr         text,
  label_it         text,
  label_rm         text,
  created_at       timestamp   NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  updated_at       timestamp   NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  CONSTRAINT topic_codes_scheme_code UNIQUE (scheme_id, code)
);

CREATE TABLE IF NOT EXISTS topics (
  id                    bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  affair_id             integer     NOT NULL REFERENCES affairs (id) ON DELETE CASCADE,
  body_id               integer     REFERENCES bodies (id),
  body_key              text,
  scheme_id             integer     NOT NULL REFERENCES topic_schemes (id),
  scheme_key            text        NOT NULL,
  level                 smallint    NOT NULL CHECK (level IN (1, 2)),   -- 1 = chapter / yes-no, 2 = subtopic
  code                  text        NOT NULL,
  parent_code           text,                                           -- level 2: chapter of the subtopic
  rank                  smallint    NOT NULL DEFAULT 1 CHECK (rank >= 1), -- 1 = the label; 2-3 = ranked suggestions
  label_de              text,                                           -- copied from topic_codes at load time
  label_fr              text,
  label_it              text,
  label_rm              text,
  p                     real        CHECK (p IS NULL OR (p >= 0 AND p <= 1)),          -- recalibrated probability
  p_raw                 real        CHECK (p_raw IS NULL OR (p_raw >= 0 AND p_raw <= 1)), -- model probability before
  lane                  text        CHECK (lane IN ('readings_agree', 'please_check')),
  status                text        NOT NULL DEFAULT 'suggested' CHECK (status IN ('suggested', 'confirmed', 'rejected')),
  provenance            text        NOT NULL DEFAULT 'inferred' CHECK (provenance IN ('inferred', 'confirmed')),
  evidence_field        text        CHECK (evidence_field IN ('title', 'title_long', 'text', 'doc')),
  evidence_text_id      integer,                                        -- texts.id when the sentence comes from a text
  evidence_doc_id       integer,                                        -- docs.id when it comes from a document
  evidence_char_start   integer,
  evidence_char_end     integer,
  evidence_quote        text,                                           -- exact substring of that field
  model                 text,                                           -- served model name
  model_build           text,                                           -- served build (system_fingerprint)
  cutoffs_id            text,                                           -- recalibration / cut-off set (aps@dd237840)
  prompt_id             text,                                           -- sha256[:12] of each exact prompt, comma-separated
  input_hash            text,                                           -- sha256[:16] of lang + title + long title + text
  content_hash          text,                                           -- hash of the row content; reloads skip equal rows
  engine_version        text,
  valid_from            timestamp   NOT NULL,
  valid_to              timestamp,
  confirmed_by          text,                                           -- decision rows: who (a person or a service)
  confirmed_by_body_id  integer     REFERENCES bodies (id),           -- set when the parliament itself publishes it
  confirmed_at          timestamp,
  created_at            timestamp   NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  updated_at            timestamp   NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  CONSTRAINT topics_version_key UNIQUE (affair_id, scheme_key, level, rank, valid_from),
  CONSTRAINT topics_machine_rows_suggest CHECK (provenance = 'confirmed' OR status = 'suggested'),
  CONSTRAINT topics_decision_has_author CHECK (provenance = 'inferred' OR (confirmed_by IS NOT NULL AND confirmed_at IS NOT NULL)),
  CONSTRAINT topics_valid_range CHECK (valid_to IS NULL OR valid_to >= valid_from),
  CONSTRAINT topics_evidence_span CHECK (evidence_char_start IS NULL OR evidence_char_end >= evidence_char_start)
);

-- API queries (Querschnitt docs/CONTRACT.md §2; resource description in ../api/topics.md)
-- GET /v1/affairs/{id}/topics                          current rows of one affair
CREATE INDEX IF NOT EXISTS topics_affair_current  ON topics (affair_id, scheme_key, level, rank) WHERE valid_to IS NULL;
-- GET /v1/topics/?scheme=&code=&status=&rank=          affairs with a code (the feed of one topic)
CREATE INDEX IF NOT EXISTS topics_code_current    ON topics (scheme_key, code, rank, status) WHERE valid_to IS NULL;
-- ... &body_key=                                        the same, one parliament
CREATE INDEX IF NOT EXISTS topics_body_current    ON topics (body_key, scheme_key, code) WHERE valid_to IS NULL;
-- ... &code=<chapter>&level=2                           subtopics under a chapter
CREATE INDEX IF NOT EXISTS topics_parent_current  ON topics (scheme_key, parent_code) WHERE valid_to IS NULL AND level = 2;
-- ?since=                                               rows opened or closed after a timestamp (re-sync, like /changes)
CREATE INDEX IF NOT EXISTS topics_updated_at      ON topics (updated_at);
-- loader: the latest machine row of a key (content-hash comparison and closing superseded rows)
CREATE INDEX IF NOT EXISTS topics_machine_key     ON topics (affair_id, scheme_key, level, rank, valid_from) WHERE provenance = 'inferred';

-- Current rows only; what the public feed reads.
CREATE OR REPLACE VIEW topics_current AS SELECT * FROM topics WHERE valid_to IS NULL;

COMMIT;
